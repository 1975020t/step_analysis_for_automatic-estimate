def test_the_migrations_and_the_models_give_the_same_schema(tmp_path):
    migrated = make_engine(f"sqlite:///{tmp_path / 'migrated.db'}")
    migrate(migrated)
    from_models = make_engine(f"sqlite:///{tmp_path / 'models.db'}")
    migrate(from_models, from_models=True)  # what an empty DSQL database gets
    for engine in (migrated, from_models):
        with engine.connect() as c:
            assert compare_metadata(MigrationContext.configure(c), Base.metadata) == []
            head = c.execute(text("SELECT version_num FROM alembic_version")).scalar_one()
        assert head == "0004"
    migrate(from_models, from_models=True)  # a second start: the migrations (none left), not create_all again
    assert set(inspect(migrated).get_table_names()) == set(inspect(from_models).get_table_names())


# ---------------------------------------------------------------- conflicts
def test_a_conflict_is_recognised_in_the_chain_of_errors():
    assert retry.is_conflict(conflict())
    try:
        try:
            raise conflict()
        except OperationalError as exc:
            raise RuntimeError("wrapped") from exc
    except RuntimeError as wrapped:
        assert retry.is_conflict(wrapped)
    assert not retry.is_conflict(OperationalError("SELECT", {}, Exception("disk full")))
    assert not retry.is_conflict(ValueError("40001"))


def test_work_runs_again_after_a_conflict_and_gives_up_after_the_attempts():
    calls = []

    def flaky():
        calls.append(1)
        if len(calls) < 3:
            raise conflict()
        return "saved"

    assert retry.retry_on_conflict(flaky) == "saved" and len(calls) == 3
    with pytest.raises(retry.ConflictError):
        retry.retry_on_conflict(lambda: (_ for _ in ()).throw(conflict()))
    calls.clear()
    with pytest.raises(ValueError):
        retry.retry_on_conflict(lambda: calls.append(1) or (_ for _ in ()).throw(ValueError("x")))
    assert len(calls) == 1  # only conflicts are run again


@pytest.fixture
def small_app(tmp_path):
    sessions = open_database(f"sqlite:///{tmp_path / 'app.db'}")
    app = FastAPI()
    app.add_middleware(ConflictRetryMiddleware)
    calls: list[dict] = []

    @app.post("/staff")
    async def add(request: Request) -> dict:
        body = await request.json()
        calls.append(body)
        with sessions() as s:
            s.add(Staff(name=f"{body['name']}{len(calls)}"))
            if body.get("commit_first"):
                s.commit()
            if len(calls) <= body["conflicts"]:
                raise conflict()
            s.commit()
        return {"calls": len(calls)}

    return TestClient(app, raise_server_exceptions=False), sessions, calls


def staff_names(sessions) -> list[str]:
    with sessions() as s:
        return list(s.scalars(select(Staff.name)))


def test_a_request_runs_again_with_the_same_body_while_nothing_was_saved(small_app):
    client, sessions, calls = small_app
    r = client.post("/staff", json={"name": "山田", "conflicts": 2})
    assert r.status_code == 200 and r.json() == {"calls": 3}
    assert calls == [{"name": "山田", "conflicts": 2}] * 3
    assert staff_names(sessions) == ["山田3"]  # the rolled-back tries left nothing


def test_a_request_that_already_saved_something_is_not_repeated(small_app):
    client, sessions, calls = small_app
    r = client.post("/staff", json={"name": "鈴木", "conflicts": 1, "commit_first": True})
    assert r.status_code == 409 and r.json()["error"]["code"] == "CONFLICT"
    assert len(calls) == 1 and staff_names(sessions) == ["鈴木1"]


def test_a_request_that_keeps_conflicting_answers_409(small_app):
    client, sessions, calls = small_app
    r = client.post("/staff", json={"name": "佐藤", "conflicts": 99})
    assert r.status_code == 409 and len(calls) == retry.ATTEMPTS and staff_names(sessions) == []


@pytest.fixture
def conflicting_commits():
    """The next `count[0]` commits of the platform fail as on DSQL (before anything is written)."""
    count = [0]

    def fail(_session) -> None:
        if count[0] > 0:
            count[0] -= 1
            raise conflict()

    event.listen(Session, "before_commit", fail)
    yield count
    event.remove(Session, "before_commit", fail)


