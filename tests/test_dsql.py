# ---------------------------------------------------------------- many rows: several transactions
def count_commits(sessions):
    seen = []
    event.listen(sessions, "after_commit", lambda _s: seen.append(1))
    return seen


def test_the_history_is_loaded_in_transactions_of_a_limited_size(tmp_path, _history_copy, monkeypatch):
    monkeypatch.setattr("src.db.seed.CHUNK", 500)
    sessions = open_database(f"sqlite:///{tmp_path / 'app.db'}")
    commits = count_commits(sessions)
    rows = len(HistoryStore(_history_copy).load())
    assert rows > 2000
    with sessions() as s:
        seed(s, platform_tests.ROOT / "data", _history_copy)
        assert s.scalar(select(func.count()).select_from(PastQuoteRow)) == rows
    assert len(commits) >= rows // 500 + 1


def test_a_large_history_import_commits_in_parts(tmp_path, _history_copy, monkeypatch):
    monkeypatch.setattr("src.services.platform.core.CHUNK", 100)

    class FakePlatform:
        def __init__(self, sessions):
            self.sessions = sessions

        def session(self):
            return self.sessions()

    sessions = open_database(f"sqlite:///{tmp_path / 'app.db'}")
    commits = count_commits(sessions)
    quotes = HistoryStore(_history_copy).load()[:450]
    assert DbHistory(FakePlatform(sessions)).append(quotes) == (450, 0)
    assert len(commits) == 5  # 4 parts of 100, then the rest with the counter
    assert DbHistory(FakePlatform(sessions)).append(quotes) == (0, 450)
