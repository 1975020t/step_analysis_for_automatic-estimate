class Orig(Exception):
    sqlstate = "40001"


def conflict() -> OperationalError:
    return OperationalError("COMMIT", {}, Orig("change conflicts with another transaction, please retry: (OC000)"))


# ---------------------------------------------------------------- the schema and the connection
def dsql_ddl() -> list[str]:
    statements: list[str] = []
    engine = create_mock_engine("auroradsql+psycopg://", lambda sql, *_, **__: statements.append(
        str(sql.compile(dialect=engine.dialect)).strip()))
    Base.metadata.create_all(engine, checkfirst=False)
    return statements


def test_the_tables_compile_for_dsql_with_64_bit_ids():
    ddl = dsql_ddl()
    tables = [s for s in ddl if s.startswith("CREATE TABLE")]
    assert len(tables) == len(Base.metadata.tables)
    assert not any("SERIAL" in s for s in ddl)
    assert all(s.startswith("CREATE INDEX ASYNC") or s.startswith("CREATE UNIQUE INDEX ASYNC")
               for s in ddl if "INDEX" in s.split("(")[0])
    for table in Base.metadata.sorted_tables:
        sql = next(s for s in tables if s.startswith(f"CREATE TABLE {table.name} "))
        for column in table.columns:
            if isinstance(column.type, BigInteger):
                assert f"\t{column.name} BIGINT" in sql, (table.name, column.name)
        if "id" in table.columns and isinstance(table.c.id.type, BigInteger):
            assert "id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (CACHE 65536)" in sql, table.name


def test_every_id_and_every_column_pointing_at_one_is_64_bit():
    for table in Base.metadata.sorted_tables:
        for column in table.columns:
            if column.foreign_keys or (column.primary_key and column.name == "id") or column.name == "current_revision_id":
                assert isinstance(column.type, BigInteger), (table.name, column.name)


